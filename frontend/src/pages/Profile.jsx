import { useState, useEffect } from 'react';
import { useAuth } from '../context/AuthContext';

const Profile = () => {
  const { user, updateProfile } = useAuth();
  const [senderEmail, setSenderEmail] = useState('');
  const [appPasskey, setAppPasskey] = useState('');
  const [message, setMessage] = useState('');
  const [error, setError] = useState('');
  const [loading, setLoading] = useState(false);

  useEffect(() => {
    if (user) {
      setSenderEmail(user.senderEmail || '');
    }
  }, [user]);

  const handleSubmit = async (e) => {
    e.preventDefault();
    setError('');
    setMessage('');

    if (senderEmail && !/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(senderEmail.trim())) {
      setError('Please enter a valid sender email');
      return;
    }

    setLoading(true);

    try {
      await updateProfile({ senderEmail: senderEmail.trim().toLowerCase(), appPasskey });
      setMessage('Profile updated successfully');
      setAppPasskey('');
    } catch (err) {
      setError(err.response?.data?.message || 'Update failed');
    } finally {
      setLoading(false);
    }
  };

  return (
    <main className="app-shell">
      <div className="mx-auto w-full max-w-3xl">
        <div className="page-header">
          <div>
            <h1 className="page-title">Profile</h1>
            <p className="page-subtitle">Update your account and sender email settings.</p>
          </div>
        </div>

        <div className="panel">
          <div className="border-b border-slate-200 px-5 py-4 sm:px-6">
            <h2 className="text-base font-semibold text-slate-950">Account information</h2>
            <p className="mt-1 text-sm text-slate-500">Your login email cannot be changed here.</p>
          </div>

          <form onSubmit={handleSubmit} className="panel-body">
            {message && (
              <div className="alert-success mb-4">
                {message}
              </div>
            )}
            {error && (
              <div className="alert-error mb-4">
                {error}
              </div>
            )}

            <div className="form-stack">
              <div>
                <label className="field-label">
                  Account Email
                </label>
                <input
                  type="email"
                  className="input-field bg-slate-50 text-slate-500"
                  value={user?.email || ''}
                  readOnly
                />
              </div>

              <div>
                <label className="field-label">
                  Sender Email
                </label>
                <input
                  type="email"
                  className="input-field"
                  placeholder="your-email@gmail.com"
                  value={senderEmail}
                  onChange={(e) => setSenderEmail(e.target.value.trimStart())}
                />
                <p className="field-help">
                  This SMTP email address is used to send tracked emails.
                </p>
              </div>

              <div>
                <label className="field-label">
                  App Passkey
                </label>
                <input
                  type="password"
                  className="input-field"
                  placeholder="Enter app password"
                  value={appPasskey}
                  onChange={(e) => setAppPasskey(e.target.value)}
                />
                <p className="field-help">
                  Use the app password generated by your email provider.
                </p>
              </div>
            </div>

            <div className="mt-6 flex justify-end">
              <button
                type="submit"
                disabled={loading}
                className="btn-primary w-full sm:w-auto"
              >
                {loading ? 'Saving...' : 'Save Changes'}
              </button>
            </div>
          </form>
        </div>
      </div>
    </main>
  );
};

export default Profile;
